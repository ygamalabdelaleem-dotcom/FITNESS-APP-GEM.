/**
 * تطبيع النص العربي للبحث الذكي (توحيد الهمزات، التاء المربوطة، الياء، وإزالة التشكيل)
 */
export function normalizeArabic(str) {
  return String(str ?? '')
    .trim()
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '') // إزالة التشكيل
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/\s+/g, ' ');
}

export function total(entries) {
  return Object.fromEntries(
    keys.map(k => [
      k,
      entries.reduce((s, e) => s + (Number(e.food[k]) || 0) * e.quantity, 0)
    ])
  );
}

export function dateKey(d = new Date()) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/**
 * حاسبة الاحتياج اليومي (Mifflin-St Jeor)
 */
export function calculateTargets({ gender, age, weight, height, activity, goal }) {
  const w = Number(weight), h = Number(height), a = Number(age);
  if (!w || !h || !a) return null;
  const bmr = 10 * w + 6.25 * h - 5 * a + (gender === 'female' ? -161 : 5);
  const mult = { sedentary: 1.2, light: 1.375, moderate: 1.55, active: 1.725 }[activity] || 1.375;
  let calories = Math.round(bmr * mult);
  if (goal === 'lose') calories = Math.max(1200, calories - 400);
  if (goal === 'gain') calories += 350;

  // البروتين: 1.6 جم لكل كجم (أو 1.8 عند التنشيف)
  const proteinFactor = goal === 'lose' ? 1.8 : 1.5;
  const protein = Math.round(w * proteinFactor);
  // الدهون: ~28% من السعرات
  const fat = Math.round((calories * 0.28) / 9);
  // الكربوهيدرات: الباقي من السعرات
  const carbs = Math.max(50, Math.round((calories - protein * 4 - fat * 9) / 4));
  // الألياف: 14 جم لكل 1000 سعرة (بحد أدنى 25 جم)
  const fiber = Math.max(25, Math.round((calories / 1000) * 14));
  // الماء: ~35 مل لكل كجم مقسوم على 250 مل للكوب
  const waterGoal = Math.max(6, Math.min(20, Math.round((w * 35) / 250)));

  return { calories, protein, carbs, fat, fiber, waterGoal };
}

function validFoodObj(f) {
  return (
    f &&
    typeof f.name === 'string' &&
    f.name.trim().length > 0 &&
    keys.every(k => Number.isFinite(f[k]) && f[k] >= 0)
  );
}

export function validBackup(x) {
  if (!x || x.version !== 1) return false;
  if (!Array.isArray(x.entries)) return false;
  const entriesOk = x.entries.every(
    e =>
      e &&
      typeof e.id === 'string' &&
      /^\d{4}-\d{2}-\d{2}$/.test(e.date) &&
      typeof e.meal === 'string' &&
      Number.isFinite(e.quantity) &&
      e.quantity > 0 &&
      e.quantity <= 20 &&
      validFoodObj(e.food)
  );
  if (!entriesOk || !x.profile) return false;

  // التحقق من الإعدادات الأساسية (مع التوافق مع النسخ الأقدم التي لا تحتوي على waterGoal)
  const baseProfileKeys = ['name', 'work', 'source', 'start', 'end', 'reminder', 'calories', 'protein', 'carbs', 'fat', 'fiber'];
  const profileOk = baseProfileKeys.every(k =>
    typeof defaults[k] === 'number'
      ? Number.isFinite(x.profile[k]) && x.profile[k] > 0
      : typeof x.profile[k] === 'string'
  );
  if (!profileOk) return false;

  if (!Array.isArray(x.supplements)) return false;
  const suppsOk = x.supplements.every(
    s => s && typeof s.id === 'string' && typeof s.name === 'string' && typeof s.note === 'string'
  );
  if (!suppsOk) return false;

  // الحقول الإضافية الاختيارية للنسخ المحدثة
  if (x.customFoods !== undefined) {
    if (!Array.isArray(x.customFoods) || !x.customFoods.every(validFoodObj)) return false;
  }
  if (x.water !== undefined && (typeof x.water !== 'object' || x.water === null)) return false;
  if (x.suppLogs !== undefined && (typeof x.suppLogs !== 'object' || x.suppLogs === null)) return false;

  return true;
}
